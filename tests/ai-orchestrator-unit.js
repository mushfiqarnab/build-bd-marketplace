// tests/ai-orchestrator-unit.js
// Pure Node unit & invariant verification for Build-BD Bilingual Voice/Text AI Orchestrator
// Verifies:
//   1. Bangla Unicode, Banglish, and English intent routing across all 5 operational verticals
//   2. Domestic Labour Sub-Tiers L1 (Daily Wage), L2 (Part-Time Chhuta Bua + appliance skill multiplier), L3 (Full-Time Driver/Homemaker)
//   3. Exact Integer-BDT 80/15/5 Weekly Thursday Payroll Split & Week-4 Continuity Reserve release
//   4. Tier 1 Micro Utility dispatch (0 BDT advance, 200 BDT visit fee, >8th floor hanging surcharge, INSTANT_OTP_T0 80/10/10 split + 2.5% spare-parts pass-through)
//   5. Tier 2 Mid Renovation Split-BOQ (43.1% labor / 44.9% paint / 8% putty / 4% protection, 20% advance, 16-bank EMI)
//   6. Tier 3 Macro Civil Tender (>500,000 BDT SSLCommerz multi-session tranche splitting)
//   7. Zero-Data 2G Feature Phone IVR / SMS / Missed-Call Gate Ping parser
'use strict';

const {
  computeDomesticWeeklySplit,
  computeMicroSettlementSplit,
  splitSslcommerzTranches,
  interpretUserUtterance,
  parseFeaturePhoneWebhook
} = require('../services/aiOrchestratorService');

let failed = 0;
function check(name, cond, detail) {
  if (cond) console.log(`  ✅ ${name}`);
  else {
    failed += 1;
    console.log(`  ❌ ${name}${detail ? ` -> ${detail}` : ''}`);
  }
}

function run() {
  console.log('🧪 Bilingual Voice/Text AI Orchestrator & Domestic/Hybrid Ledger Unit Suite');

  // 1. Domestic Labour L2 (Bangla Unicode with Washing Machine appliance certification)
  const domL2 = interpretUserUtterance('ধানমন্ডি ৭ নাম্বার রোডে প্রতিদিন ২ ঘণ্টা কাজের জন্য একজন ছুটা বুয়া লাগবে, রান্না আর ওয়াশিং মেশিন চালাতে পারলে ভালো');
  check('Bangla utterance routes to DOMESTIC_LABOUR L2_PART_TIME_MONTHLY',
    domL2.vertical === 'DOMESTIC_LABOUR' && domL2.subTier === 'L2_PART_TIME_MONTHLY');
  check('Extracts Dhanmondi thana and 2h shift',
    domL2.extractedSlots.thana === 'Dhanmondi' && domL2.extractedSlots.shiftHours === 2);
  check('Appliance certification (Washing Machine) triggers >= 9,000 BDT monthly tier',
    domL2.pricingEstimate.agreedMonthlyOrDailyBdt >= 9000);
  check('Enforces Ring 1 Porichoy (>=80% face match, 18+), Ring 2 (2 guarantors), Ring 3 DMP CIMS',
    domL2.trustAndCompliance.ring1PorichoyBiometric.requiredFaceMatchPct === 80 &&
    domL2.trustAndCompliance.ring2DigitalDarwanGuarantors.minActiveGuarantors === 2 &&
    domL2.trustAndCompliance.ring3DmpCimsDossier.autoGeneratedPdfAndJson === true);

  // 2. Domestic Weekly 80/15/5 Integer BDT Split & Week 4 Reserve Release
  const wk1 = computeDomesticWeeklySplit(1050, 1, 0);
  check('Week 1 80/15/5 split produces exact integer BDT values summing to gross (1050)',
    Number.isInteger(wk1.workerImmediateBdt) &&
    Number.isInteger(wk1.continuityHoldBdt) &&
    Number.isInteger(wk1.platformFeeBdt) &&
    (wk1.workerImmediateBdt + wk1.continuityHoldBdt + wk1.platformFeeBdt === 1050));

  const wk4 = computeDomesticWeeklySplit(1050, 4, wk1.continuityHoldBdt * 3);
  check('Week 4 releases 95% of Week 4 + 100% of accumulated 3-week continuity reserve',
    wk4.continuityHoldBdt === 0 &&
    wk4.reserveReleasedBdt === wk1.continuityHoldBdt * 3 &&
    wk4.workerImmediateBdt === (1050 - wk4.platformFeeBdt) + wk1.continuityHoldBdt * 3);

  // 3. Domestic Labour L3 Full-Time Driver (Banglish)
  const domL3 = interpretUserUtterance('Gulshan e 10 hours er jonno ekjon personal car driver lagbe');
  check('Banglish driver query routes to DOMESTIC_LABOUR L3_FULL_TIME_MONTHLY PERSONAL_DRIVER',
    domL3.vertical === 'DOMESTIC_LABOUR' &&
    domL3.subTier === 'L3_FULL_TIME_MONTHLY' &&
    domL3.workerCategory === 'PERSONAL_DRIVER');

  // 4. Tier 1 Micro Utility (Banglish with 10th floor outdoor hanging surcharge)
  const microAc = interpretUserUtterance('Uttara 10 তলায় এসি থেকে পানি পড়ছে, আজকেই সার্ভিসিং মিস্ত্রি লাগবে');
  check('AC repair utterance routes to TIER_1_MICRO with 0 BDT advance & 200 BDT visit fee floor',
    microAc.vertical === 'TIER_1_MICRO' &&
    microAc.pricingEstimate.bookingAdvanceBdt === 0 &&
    microAc.pricingEstimate.visitingFeeFloorBdt === 200);
  check('Floor 10 (>8th floor) appends 800 BDT outdoor hanging surcharge',
    microAc.extractedSlots.floorLevel === 10 &&
    microAc.pricingEstimate.contextualSurchargesBdt === 800 &&
    microAc.pricingEstimate.totalBaseEscrowOnArrivalBdt === 1600);

  // Verify Micro Spare Parts 2.5% gateway pass-through calculation (1000 labor + 500 part)
  const microSplit = computeMicroSettlementSplit(1000, 500);
  check('Micro settlement split: integer BDT with 80% labor + 97.5% spare part reimbursement',
    Number.isInteger(microSplit.immediateTechnicianPayoutBdt) &&
    microSplit.laborImmediateBdt === 800 &&
    microSplit.warrantyHold7DayBdt === 100 &&
    microSplit.partsNetReimbursementBdt === 487);

  // 5. Tier 2 Mid Apartment Painting Split-BOQ
  const midPaint = interpretUserUtterance('মিরপুরে ১৮০০ স্কয়ার ফিট ফ্ল্যাট পেইন্টিং করব বিয়ের আগে');
  check('1800 sqft painting utterance routes to TIER_2_MID with BOQ_SPLIT_CART and 16-bank EMI',
    midPaint.vertical === 'TIER_2_MID' &&
    midPaint.extractedSlots.areaSqft === 1800 &&
    midPaint.extractedSlots.materialMode === 'BOQ_SPLIT_CART' &&
    midPaint.extractedSlots.emiEligible16Banks === true);
  const boq = midPaint.pricingEstimate.boqSplitBreakdown;
  check('Tier 2 Split-BOQ components sum exactly to totalEstimatedBdt in integer BDT',
    (boq.laborBdt + boq.materialKitBdt + boq.puttyAndPrepBdt + boq.accessProtectionBdt) === midPaint.pricingEstimate.totalEstimatedBdt);

  // 6. Direct Bulk Materials Order (150 bags full truckload with 10% open storage wastage)
  const matOrder = interpretUserUtterance('উত্তরায় ১৫০ বস্তা শাহ সিমেন্ট লাগবে খোলা জায়গায় রাখার জন্য ১০% ঘাটতি ধরে');
  check('Cement truckload utterance routes to MATERIALS_DIRECT with 10% wastage buffer (165 bags)',
    matOrder.vertical === 'MATERIALS_DIRECT' &&
    matOrder.extractedSlots.requestedQty === 150 &&
    matOrder.extractedSlots.wastageBufferPct === 10 &&
    matOrder.extractedSlots.adjustedQty === 165 &&
    matOrder.pricingEstimate.settlementRail === 'BANK_BEFTN_RTGS');

  // 7. Tier 3 Macro SSLCommerz <= 500,000 BDT Tranche Splitter
  const tranches = splitSslcommerzTranches(1200000, 'BBD-MACRO');
  check('1,200,000 BDT milestone splits into 3 SSLCommerz tranches each <= 500,000 BDT summing to 1,200,000',
    tranches.length === 3 &&
    tranches.every((t) => t.amount_bdt <= 500000 && Number.isInteger(t.amount_bdt)) &&
    tranches.reduce((s, t) => s + t.amount_bdt, 0) === 1200000);

  // 8. 2G Feature Phone IVR / SMS / Missed-Call Webhook Parser
  const missedCall = parseFeaturePhoneWebhook({ fromPhone: '01712345678', digitsOrText: '', callType: 'MISSED_CALL_RING_DROP' });
  const dtmfAccept = parseFeaturePhoneWebhook({ fromPhone: '01712345678', digitsOrText: '১' });
  const safetyFlag = parseFeaturePhoneWebhook({ fromPhone: '01712345678', digitsOrText: '৯' });
  const reverseOtp = parseFeaturePhoneWebhook({ fromPhone: '01712345678', digitsOrText: '৪৮২৯' });
  check('2G Missed-Call logs PRESENT_AUTO_GATE_PING at 0 BDT cost',
    missedCall.action === 'LOG_ATTENDANCE_GATE_PING' && missedCall.costBdt === 0);
  check('Bengali digit ১ accepts shift offer', dtmfAccept.action === 'ACCEPT_SHIFT_OR_CONFIRM_ATTENDANCE');
  check('Bengali digit ৯ triggers CRITICAL_SLA_2H DWPWP-2015 safety/wage escalation',
    safetyFlag.action === 'EMERGENCY_SAFETY_OR_WAGE_DISPUTE_ESCALATION');
  check('4-digit Bengali code ৪৮২৯ normalizes to 4829 and computes SHA-256 reverse-OTP hash',
    reverseOtp.action === 'VERIFY_DAILY_REVERSE_OTP' && reverseOtp.otpCode === '4829' && reverseOtp.otpHash.length === 64);

  console.log(`--- Results: ${failed === 0 ? 'all passed' : `${failed} failed`} ---`);
  process.exit(failed === 0 ? 0 : 1);
}

run();
